import React, { useState, useEffect } from 'react';
import { Link } from 'react-router-dom';
import { useLanguage } from '../context/LanguageContext';
import { summarizeOrder } from '../services/api';
import {
  FileText,
  Download,
  Calendar,
  Building,
  Tag,
  ArrowRight,
  Bot,
  Loader2,
  X,
  RotateCcw,
} from 'lucide-react';

const OrderCard = ({ order }) => {
  const { getLocalized, t, language } = useLanguage();

  const title = getLocalized(order.title);
  const description = getLocalized(order.description);
  const formattedDate = new Date(order.publicationDate).toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  });

  // AI Summary State
  const [showAiSummary, setShowAiSummary] = useState(false);
  const [aiSummaries, setAiSummaries] = useState({}); // { [lang]: string[] }
  const [aiLoading, setAiLoading] = useState(false);
  const [aiError, setAiError] = useState(null);

  const getPdfFullUrl = (url) => {
    if (!url) return '#';
    if (url.startsWith('http')) return url;
    const base = import.meta.env.PROD
      ? window.location.origin
      : (import.meta.env.VITE_SOCKET_URL || 'http://localhost:5000');
    return `${base}${url}`;
  };

  const fetchSummaryForLang = async (lang, force = false) => {
    if (!force && aiSummaries[lang]) return;
    setAiLoading(true);
    setAiError(null);
    try {
      const activeTitle = order.title[lang] || order.title.en || title;
      const activeDesc = order.description[lang] || order.description.en || description;
      const res = await summarizeOrder({
        title: activeTitle,
        description: activeDesc,
        language: lang,
      });
      if (res.success && Array.isArray(res.bullets)) {
        setAiSummaries((prev) => ({ ...prev, [lang]: res.bullets }));
      } else {
        setAiError(res.message || 'AI summary unavailable.');
      }
    } catch (err) {
      setAiError(err.response?.data?.message || 'Unable to connect to AI summary service. Please try again.');
    } finally {
      setAiLoading(false);
    }
  };

  const handleToggleAiSummary = () => {
    if (!showAiSummary) {
      setShowAiSummary(true);
      if (!aiSummaries[language]) {
        fetchSummaryForLang(language);
      }
    } else {
      setShowAiSummary(false);
    }
  };

  useEffect(() => {
    if (showAiSummary && !aiSummaries[language]) {
      fetchSummaryForLang(language);
    }
  }, [language, showAiSummary]);

  const activeBullets = aiSummaries[language] || [];

  return (
    <article className="bg-white rounded-md border border-[#DFE3E8] hover:border-[#CFD6DE] shadow-xs hover:shadow-cardHover transition-all duration-150 flex flex-col justify-between overflow-hidden">
      {/* Top Gazette Ledger Header Bar */}
      <div className="bg-[#F1F3F5] border-b border-[#DFE3E8] px-4 py-2.5 flex flex-wrap items-center justify-between gap-2">
        <div className="flex items-center space-x-2">
          <span className="px-2 py-0.5 rounded-md bg-white text-[#181A1B] text-[11px] font-bold font-mono tracking-wide border border-[#DFE3E8] tabular-nums">
            {order.orderNumber}
          </span>
          <span className="text-[11px] text-[#495057] bg-white px-2 py-0.5 rounded-md border border-[#DFE3E8] font-medium">
            {order.category}
          </span>
        </div>

        <div className="flex items-center text-[11px] text-[#6C757D] font-medium tabular-nums">
          <Calendar className="w-3.5 h-3.5 mr-1 text-[#6C757D]" />
          <span>{formattedDate}</span>
        </div>
      </div>

      {/* Main Content Area */}
      <div className="p-4 sm:p-5 flex-1 flex flex-col">
        <div className="mb-2 flex items-center text-[11px] font-semibold text-[#495057]">
          <Building className="w-3.5 h-3.5 mr-1.5 text-[#6C757D]" />
          <span>{order.department}</span>
        </div>

        <Link
          to={`/orders/${order._id}`}
          className="font-sans text-base font-bold text-[#181A1B] hover:text-[#B84A00] leading-snug line-clamp-2 transition mb-2"
        >
          {title}
        </Link>

        <p className="text-xs text-[#495057] line-clamp-3 leading-relaxed flex-1">
          {description}
        </p>

        {/* AI Plain-Language Summary Callout Box */}
        {showAiSummary && (
          <div className="mt-3 p-3 bg-[#F1F3F5] border border-[#DFE3E8] rounded-md text-xs space-y-1.5 animate-in fade-in duration-150">
            <div className="flex items-center justify-between">
              <span className="text-[10px] font-bold text-[#B84A00] uppercase tracking-wider flex items-center gap-1 font-sans">
                <Bot className="w-3.5 h-3.5" />
                Plain-language summary generated by AI ({language.toUpperCase()})
              </span>
              <div className="flex items-center space-x-1">
                {aiLoading && <Loader2 className="w-3 h-3 animate-spin text-[#6C757D]" />}
                <button
                  type="button"
                  onClick={() => setShowAiSummary(false)}
                  className="text-[#6C757D] hover:text-[#181A1B] p-0.5 rounded-md"
                  title="Close AI Summary"
                >
                  <X className="w-3.5 h-3.5" />
                </button>
              </div>
            </div>

            {aiError ? (
              <div className="flex items-center justify-between gap-2 p-2 bg-red-50/80 border border-red-200 rounded-md">
                <p className="text-[11px] text-red-700 leading-snug">{aiError}</p>
                <button
                  type="button"
                  onClick={() => fetchSummaryForLang(language, true)}
                  className="inline-flex items-center space-x-1 px-2 py-0.5 bg-white hover:bg-[#F1F3F5] text-[#181A1B] border border-[#DFE3E8] rounded-md text-[10px] font-bold shadow-xs shrink-0 transition"
                >
                  <RotateCcw className="w-2.5 h-2.5 text-[#B84A00]" />
                  <span>Retry</span>
                </button>
              </div>
            ) : activeBullets.length > 0 ? (
              <ul className="space-y-1 text-[#181A1B] text-[11px] list-disc list-inside leading-relaxed">
                {activeBullets.map((bullet, idx) => (
                  <li key={idx} className="leading-snug">
                    {bullet}
                  </li>
                ))}
              </ul>
            ) : aiLoading ? (
              <p className="text-[11px] text-[#6C757D] italic">Generating 3-bullet summary in {language.toUpperCase()}...</p>
            ) : null}
          </div>
        )}
      </div>

      {/* Action Footer */}
      <div className="px-4 py-3 bg-[#F8F9FA] border-t border-[#DFE3E8] flex flex-wrap items-center justify-between gap-2">
        <Link
          to={`/orders/${order._id}`}
          className="inline-flex items-center text-xs font-bold text-[#181A1B] hover:text-[#B84A00] transition"
        >
          <span>{t('viewDetails')}</span>
          <ArrowRight className="w-3.5 h-3.5 ml-1" />
        </Link>

        <div className="flex items-center space-x-2">
          {/* Dedicated AI Summary Button (NOT a dropdown) */}
          <button
            type="button"
            onClick={handleToggleAiSummary}
            className={`inline-flex items-center space-x-1.5 px-2.5 py-1 rounded-md text-xs font-semibold shadow-xs transition ${
              showAiSummary
                ? 'bg-[#181A1B] text-white hover:bg-[#2C3034]'
                : 'bg-white hover:bg-[#F1F3F5] text-[#181A1B] border border-[#DFE3E8]'
            }`}
            title="Generate AI plain-language summary in active language"
          >
            {aiLoading ? (
              <Loader2 className="w-3.5 h-3.5 animate-spin text-[#B84A00]" />
            ) : (
              <Bot className="w-3.5 h-3.5 text-[#B84A00]" />
            )}
            <span>AI Summary</span>
          </button>

          {order.pdfUrl ? (
            <a
              href={getPdfFullUrl(order.pdfUrl)}
              target="_blank"
              rel="noopener noreferrer"
              download
              className="inline-flex items-center space-x-1.5 bg-white hover:bg-[#F1F3F5] text-[#181A1B] border border-[#DFE3E8] px-2.5 py-1 rounded-md text-xs font-semibold shadow-xs transition"
              title={t('downloadPdf')}
            >
              <Download className="w-3 h-3 text-[#B84A00]" />
              <span>PDF</span>
            </a>
          ) : (
            <span className="text-[11px] text-[#6C757D] italic">No document</span>
          )}
        </div>
      </div>
    </article>
  );
};

export default OrderCard;
